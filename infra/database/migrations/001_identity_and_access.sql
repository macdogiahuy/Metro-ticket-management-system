-- Keep the existing IdentityDbContext<string> table names and key types.
-- Identity credential rows may cascade; domain/history references below restrict deletion.
CREATE TABLE IF NOT EXISTS public."AspNetUsers" (
    "Id" text PRIMARY KEY,
    "UserName" varchar(256), "NormalizedUserName" varchar(256),
    "Email" varchar(256), "NormalizedEmail" varchar(256),
    "EmailConfirmed" boolean NOT NULL,
    "PasswordHash" text, "SecurityStamp" text, "ConcurrencyStamp" text,
    "PhoneNumber" text, "PhoneNumberConfirmed" boolean NOT NULL,
    "TwoFactorEnabled" boolean NOT NULL,
    "LockoutEnd" timestamptz, "LockoutEnabled" boolean NOT NULL,
    "AccessFailedCount" integer NOT NULL
);
CREATE TABLE IF NOT EXISTS public."AspNetRoles" (
    "Id" text PRIMARY KEY, "Name" varchar(256), "NormalizedName" varchar(256),
    "ConcurrencyStamp" text
);
CREATE TABLE IF NOT EXISTS public."AspNetUserClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "UserId" text NOT NULL REFERENCES public."AspNetUsers" ("Id") ON DELETE CASCADE,
    "ClaimType" text, "ClaimValue" text
);
CREATE TABLE IF NOT EXISTS public."AspNetRoleClaims" (
    "Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RoleId" text NOT NULL REFERENCES public."AspNetRoles" ("Id") ON DELETE CASCADE,
    "ClaimType" text, "ClaimValue" text
);
CREATE TABLE IF NOT EXISTS public."AspNetUserLogins" (
    "LoginProvider" text NOT NULL, "ProviderKey" text NOT NULL, "ProviderDisplayName" text,
    "UserId" text NOT NULL REFERENCES public."AspNetUsers" ("Id") ON DELETE CASCADE,
    PRIMARY KEY ("LoginProvider", "ProviderKey")
);
CREATE TABLE IF NOT EXISTS public."AspNetUserRoles" (
    "UserId" text NOT NULL REFERENCES public."AspNetUsers" ("Id") ON DELETE CASCADE,
    "RoleId" text NOT NULL REFERENCES public."AspNetRoles" ("Id") ON DELETE CASCADE,
    PRIMARY KEY ("UserId", "RoleId")
);
CREATE TABLE IF NOT EXISTS public."AspNetUserTokens" (
    "UserId" text NOT NULL REFERENCES public."AspNetUsers" ("Id") ON DELETE CASCADE,
    "LoginProvider" text NOT NULL, "Name" text NOT NULL, "Value" text,
    PRIMARY KEY ("UserId", "LoginProvider", "Name")
);
CREATE UNIQUE INDEX IF NOT EXISTS "UserNameIndex" ON public."AspNetUsers" ("NormalizedUserName");
CREATE INDEX IF NOT EXISTS "EmailIndex" ON public."AspNetUsers" ("NormalizedEmail");
CREATE UNIQUE INDEX IF NOT EXISTS "UX_AspNetUsers_NormalizedEmail"
    ON public."AspNetUsers" ("NormalizedEmail") WHERE "NormalizedEmail" IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS "RoleNameIndex" ON public."AspNetRoles" ("NormalizedName");
CREATE INDEX IF NOT EXISTS "IX_AspNetUserClaims_UserId" ON public."AspNetUserClaims" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_AspNetRoleClaims_RoleId" ON public."AspNetRoleClaims" ("RoleId");
CREATE INDEX IF NOT EXISTS "IX_AspNetUserLogins_UserId" ON public."AspNetUserLogins" ("UserId");
CREATE INDEX IF NOT EXISTS "IX_AspNetUserRoles_RoleId" ON public."AspNetUserRoles" ("RoleId");

CREATE TABLE metro.operators (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), code varchar(40) NOT NULL UNIQUE,
    name text NOT NULL, timezone text NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','INACTIVE')),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE metro.banks (
    code varchar(40) PRIMARY KEY, name text NOT NULL, is_demo boolean NOT NULL DEFAULT true
);

CREATE TABLE metro.user_profiles (
    user_id text PRIMARY KEY REFERENCES public."AspNetUsers" ("Id"),
    full_name text NOT NULL CHECK (btrim(full_name) <> ''),
    normalized_full_name text NOT NULL, birth_date date NOT NULL,
    -- Validate twelve digits before encryption. Use a keyed HMAC for exact-match lookup.
    citizen_id_ciphertext bytea, citizen_id_lookup_hash char(64) UNIQUE,
    citizen_id_last4 varchar(4) CHECK (citizen_id_last4 ~ '^[0-9]{4}$'),
    citizen_id_verified_at timestamptz,
    bank_code varchar(40) REFERENCES metro.banks (code), bank_account_ciphertext bytea,
    bank_account_last4 varchar(4), bank_holder_name text,
    status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','ACTIVE','LOCKED','DISABLED','CLOSED')),
    locale varchar(20) NOT NULL DEFAULT 'vi-VN', email_notifications boolean NOT NULL DEFAULT true,
    registered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    next_eligibility_review_at timestamptz, eligibility_review_number integer NOT NULL DEFAULT 1 CHECK (eligibility_review_number > 0),
    terms_accepted_at timestamptz,
    anonymized_at timestamptz, anonymization_reason text,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((citizen_id_ciphertext IS NULL AND citizen_id_lookup_hash IS NULL AND citizen_id_last4 IS NULL AND citizen_id_verified_at IS NULL)
        OR (citizen_id_ciphertext IS NOT NULL AND citizen_id_lookup_hash IS NOT NULL AND citizen_id_last4 IS NOT NULL)),
    CHECK (citizen_id_lookup_hash IS NULL OR citizen_id_lookup_hash ~ '^[0-9a-f]{64}$'),
    CHECK ((bank_code IS NULL AND bank_account_ciphertext IS NULL AND bank_holder_name IS NULL AND bank_account_last4 IS NULL)
        OR (bank_code IS NOT NULL AND bank_account_ciphertext IS NOT NULL AND bank_holder_name IS NOT NULL AND bank_account_last4 IS NOT NULL)),
    CHECK (anonymized_at IS NULL OR nullif(btrim(anonymization_reason),'') IS NOT NULL)
);

CREATE TABLE metro.auth_sessions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id text NOT NULL REFERENCES public."AspNetUsers" ("Id"),
    refresh_token_hash char(64) NOT NULL UNIQUE CHECK (refresh_token_hash ~ '^[0-9a-f]{64}$'),
    issued_at timestamptz NOT NULL DEFAULT clock_timestamp(), last_active_at timestamptz,
    expires_at timestamptz NOT NULL, revoked_at timestamptz, revocation_reason text,
    device_summary text, CHECK (expires_at > issued_at)
);

CREATE TABLE metro.email_verification_challenges (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id text NOT NULL REFERENCES public."AspNetUsers" ("Id"),
    purpose text NOT NULL CHECK (purpose IN ('VERIFY_EMAIL','RESET_PASSWORD','MFA')),
    code_hash char(64) NOT NULL CHECK (code_hash ~ '^[0-9a-f]{64}$'),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(), expires_at timestamptz NOT NULL,
    failed_attempts smallint NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    consumed_at timestamptz, superseded_at timestamptz,
    delivery_status text NOT NULL DEFAULT 'PENDING' CHECK (delivery_status IN ('PENDING','SENT','FAILED')),
    CHECK (expires_at = created_at + interval '10 minutes')
);
CREATE UNIQUE INDEX uq_active_email_challenge ON metro.email_verification_challenges (user_id, purpose)
    WHERE consumed_at IS NULL AND superseded_at IS NULL;

CREATE TABLE metro.operator_accounts (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), operator_id uuid NOT NULL REFERENCES metro.operators (id),
    user_id text NOT NULL REFERENCES public."AspNetUsers" ("Id"),
    account_type text NOT NULL CHECK (account_type IN ('PASSENGER','STAFF','ADMIN')),
    status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','LOCKED','DISABLED','CLOSED')),
    mfa_required boolean NOT NULL DEFAULT false,
    UNIQUE (operator_id, id), UNIQUE (operator_id, user_id),
    CHECK (account_type = 'PASSENGER' OR mfa_required)
);

CREATE TABLE metro.business_roles (
    code varchar(60) PRIMARY KEY, name text NOT NULL, actor_code varchar(20),
    is_privileged boolean NOT NULL DEFAULT false
);
CREATE TABLE metro.permissions (
    code varchar(80) PRIMARY KEY, description text NOT NULL
);
CREATE TABLE metro.role_permissions (
    role_code varchar(60) NOT NULL REFERENCES metro.business_roles (code),
    permission_code varchar(80) NOT NULL REFERENCES metro.permissions (code),
    version integer NOT NULL DEFAULT 1 CHECK (version > 0),
    PRIMARY KEY (role_code, permission_code, version)
);
CREATE TABLE metro.account_role_assignments (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), operator_id uuid NOT NULL REFERENCES metro.operators (id),
    account_id uuid NOT NULL, role_code varchar(60) NOT NULL REFERENCES metro.business_roles (code),
    valid_from timestamptz NOT NULL DEFAULT clock_timestamp(), valid_to timestamptz,
    granted_by_user_id text REFERENCES public."AspNetUsers" ("Id"), reason text NOT NULL CHECK (btrim(reason) <> ''),
    revoked_at timestamptz, revoked_by_user_id text REFERENCES public."AspNetUsers" ("Id"),
    UNIQUE (operator_id, id), FOREIGN KEY (operator_id, account_id) REFERENCES metro.operator_accounts (operator_id, id),
    CHECK (valid_to IS NULL OR valid_to > valid_from),
    EXCLUDE USING gist (operator_id WITH =, account_id WITH =, role_code WITH =,
        tstzrange(valid_from, valid_to, '[)') WITH &&) WHERE (revoked_at IS NULL)
);

CREATE TABLE metro.audit_logs (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), operator_id uuid REFERENCES metro.operators (id),
    actor_user_id text REFERENCES public."AspNetUsers" ("Id"), database_actor text NOT NULL DEFAULT current_user,
    action text NOT NULL, entity_type text NOT NULL, entity_id text NOT NULL,
    changed_fields text[] NOT NULL DEFAULT '{}', before_hash char(64), after_hash char(64),
    reason text, outcome text NOT NULL DEFAULT 'SUCCEEDED',
    occurred_at timestamptz NOT NULL DEFAULT clock_timestamp(), correlation_id uuid NOT NULL DEFAULT gen_random_uuid(),
    UNIQUE (operator_id, id)
);
CREATE INDEX ix_audit_operator_time ON metro.audit_logs (operator_id, occurred_at DESC);
CREATE INDEX ix_audit_entity ON metro.audit_logs (operator_id, entity_type, entity_id);
CREATE INDEX ix_audit_correlation ON metro.audit_logs (correlation_id);
COMMENT ON TABLE metro.audit_logs IS 'Append-only, with hashes and changed column names; never copy raw PII, token or document content here.';

CREATE TABLE metro.system_config_versions (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), operator_id uuid NOT NULL REFERENCES metro.operators (id),
    config_group varchar(60) NOT NULL, version integer NOT NULL CHECK (version > 0),
    settings jsonb NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(settings) = 'object'),
    secret_reference text, effective_from timestamptz NOT NULL, effective_to timestamptz,
    status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PENDING_APPROVAL','APPROVED','PUBLISHED','SUPERSEDED','EXPIRED','REJECTED','CANCELLED')),
    approved_by_user_id text REFERENCES public."AspNetUsers" ("Id"), approved_at timestamptz,
    published_by_user_id text REFERENCES public."AspNetUsers" ("Id"), published_at timestamptz,
    is_seed boolean NOT NULL DEFAULT false, source_refs jsonb NOT NULL DEFAULT '[]',
    UNIQUE (operator_id, id), UNIQUE (operator_id, config_group, version),
    CHECK (effective_to IS NULL OR effective_to > effective_from),
    EXCLUDE USING gist (operator_id WITH =, config_group WITH =, tstzrange(effective_from, effective_to, '[)') WITH &&)
        WHERE (status = 'PUBLISHED')
);
COMMENT ON COLUMN metro.system_config_versions.secret_reference IS 'Reference to an application secret store; never store the secret itself.';

CREATE TABLE metro.retention_policies (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(), operator_id uuid NOT NULL REFERENCES metro.operators (id),
    entity_type varchar(80) NOT NULL, version integer NOT NULL CHECK (version > 0),
    retention_days integer CHECK (retention_days >= 0), action text NOT NULL CHECK (action IN ('RETAIN','DELETE_EVIDENCE','ANONYMIZE')),
    status text NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT','PENDING_APPROVAL','APPROVED','PUBLISHED','SUPERSEDED','EXPIRED','REJECTED','CANCELLED')),
    enabled boolean NOT NULL DEFAULT false, effective_from timestamptz NOT NULL, effective_to timestamptz,
    approved_by_user_id text REFERENCES public."AspNetUsers" ("Id"), approved_at timestamptz,
    published_by_user_id text REFERENCES public."AspNetUsers" ("Id"), published_at timestamptz,
    is_seed boolean NOT NULL DEFAULT false, source_refs jsonb NOT NULL DEFAULT '[]',
    UNIQUE (operator_id, id), UNIQUE (operator_id, entity_type, version),
    CHECK (NOT enabled OR (approved_by_user_id IS NOT NULL AND status = 'PUBLISHED')),
    CHECK (effective_to IS NULL OR effective_to > effective_from)
);
